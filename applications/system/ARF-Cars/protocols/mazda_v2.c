SubGhzProtocolStatus
    subghz_protocol_encoder_mazda_v2_deserialize(void* context, FlipperFormat* flipper_format) {
    furi_check(context);
    SubGhzProtocolEncoderMazdaV2* instance = context;
    SubGhzProtocolStatus ret = SubGhzProtocolStatusError;

    instance->encoder.is_running = false;
    instance->encoder.front = 0;

    do {
        flipper_format_rewind(flipper_format);
        if(subghz_block_generic_deserialize_check_count_bit(
               &instance->generic,
               flipper_format,
               subghz_protocol_mazda_v2_const.min_count_bit_for_found) != SubGhzProtocolStatusOk) {
            break;
        }

        mazda_v2_decode_key(&instance->generic);

        uint8_t hop[6];
        uint8_t idx;
        uint8_t hdr;
        uint8_t btn;
        mazda_v2_extract(instance->generic.data, hop, &idx, &hdr, &btn);
        const bool inline_layout = mazda_v2_layout_is_inline(hop[0], btn);

        uint8_t delta[6];
        const uint8_t* row = mazda_v2_table_row(btn, idx);
        bool mismatch = false;
        for(uint8_t i = 0; i < 6; i++) {
            delta[i] = (uint8_t)(hop[i] ^ row[i]);
            if(delta[i]) {
                mismatch = true;
            }
        }
        const uint8_t xor_idx_bits = (uint8_t)((idx >> 1) & 3U);

        uint32_t serial = instance->generic.serial;
        uint32_t btn32 = btn;
        uint32_t cnt = idx;
        uint32_t hdr32 = hdr;
        flipper_format_rewind(flipper_format);
        flipper_format_read_uint32(flipper_format, "Serial", &serial, 1);
        flipper_format_rewind(flipper_format);
        flipper_format_read_uint32(flipper_format, "Btn", &btn32, 1);
        flipper_format_rewind(flipper_format);
        flipper_format_read_uint32(flipper_format, "Cnt", &cnt, 1);
        flipper_format_rewind(flipper_format);
        flipper_format_read_uint32(flipper_format, "Hdr", &hdr32, 1);
        UNUSED(serial);

        btn = (uint8_t)btn32;
        hdr = (uint8_t)hdr32;
        cnt &= 0xFFU;

        const uint8_t btn_hi = (uint8_t)(btn & 0x80U);
        if((subghz_custom_btn_get_original() == 0)) {
            subghz_custom_btn_set_original((uint8_t)(btn & 0x7FU));
        }
        subghz_custom_btn_set_max(MAZDA_V2_BTN_MAX);
        btn = (uint8_t)((mazda_v2_get_btn_code() & 0x7FU) | btn_hi);
        subghz_block_generic_global_button_override_get(&btn);

        if(!subghz_block_generic_global_counter_override_get(&cnt)) {
            const int32_t mult = furi_hal_subghz_get_rolling_counter_mult();
            if(mult != -0x7FFFFFFF) {
                cnt = (uint8_t)(cnt + (uint32_t)mult);
            }
        } else {
            cnt &= 0xFFU;
        }

        uint8_t new_hop[6];
        if(inline_layout) {
            memcpy(new_hop, hop, sizeof(new_hop));
            mazda_v2_inline_apply_idx(new_hop, (uint8_t)cnt);
        } else {
            mazda_v2_advance_hop(new_hop, (uint8_t)cnt, btn, mismatch, xor_idx_bits, delta);
        }
        instance->generic.data = mazda_v2_pack(new_hop, (uint8_t)cnt, hdr, btn);
        instance->generic.data_count_bit = subghz_protocol_mazda_v2_const.min_count_bit_for_found;
        mazda_v2_decode_key(&instance->generic);

        flipper_format_rewind(flipper_format);
        if(!flipper_format_read_uint32(
               flipper_format, "Repeat", (uint32_t*)&instance->encoder.repeat, 1)) {
            instance->encoder.repeat = 3;
        }

        if(!mazda_v2_build_upload(instance)) {
            break;
        }

        flipper_format_rewind(flipper_format);
        uint8_t key_data[sizeof(uint64_t)];
        for(size_t i = 0; i < sizeof(uint64_t); i++) {
            key_data[i] = (uint8_t)(instance->generic.data >> ((7U - i) * 8U));
        }
        if(!flipper_format_update_hex(flipper_format, "Key", key_data, sizeof(key_data))) {
            break;
        }
        uint32_t btn_w = instance->generic.btn;
        uint32_t cnt_w = instance->generic.cnt;
        flipper_format_insert_or_update_uint32(flipper_format, "Btn", &btn_w, 1);
        flipper_format_insert_or_update_uint32(flipper_format, "Cnt", &cnt_w, 1);
        subghz_block_generic_global.current_cnt = instance->generic.cnt;

        instance->encoder.is_running = true;
        ret = SubGhzProtocolStatusOk;
    } while(false);

    return ret;
}

